/**
 * 將中文字串轉為帶 <ruby> 注音的 HTML。
 * 不在字典內的字（標點、英文、數字、罕用字）原樣輸出。
 *
 * @param {string} text  原始中文字串
 * @returns {string}     含 <ruby><rt> 的 HTML 字串
 */
function toRuby(text) {
  return [...text].map(char => {
    const rt = BPMF[char];
    return rt
      ? `<ruby>${char}<rt>${rt}</rt></ruby>`
      : char;
  }).join('');
}

/**
 * 批次轉換 DOM 元素的 textContent → innerHTML（含注音）。
 * 呼叫方式：rubyDOM('.task-note, .story-intro')
 *
 * @param {string} selector  CSS 選擇器
 */
function rubyDOM(selector) {
  document.querySelectorAll(selector).forEach(el => {
    el.innerHTML = toRuby(el.textContent);
  });
}

